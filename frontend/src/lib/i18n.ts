export const LANGS = ["en", "tl", "ceb", "es", "ja"] as const;
export type Lang = (typeof LANGS)[number];

export const INTERFACE_LANGUAGES: { id: Lang; label: string }[] = [
  { id: "en", label: "English" },
  { id: "tl", label: "Tagalog" },
  { id: "ceb", label: "Visayan (Bisaya)" },
  { id: "es", label: "Español" },
  { id: "ja", label: "日本語" },
];

const CLOCK: Record<Lang, string> = {
  en: "en-US",
  tl: "fil-PH",
  ceb: "ceb",
  es: "es-ES",
  ja: "ja-JP",
};

export function normalizeLang(raw?: string | null): Lang {
  const value = (raw || "en").toLowerCase();
  if (value === "tl" || value === "fil" || value.startsWith("tagalog")) return "tl";
  if (
    value === "ceb" ||
    value === "bis" ||
    value.startsWith("visayan") ||
    value.startsWith("bisaya")
  ) {
    return "ceb";
  }
  if (value.startsWith("es")) return "es";
  if (value.startsWith("ja")) return "ja";
  return "en";
}

export function clockLocale(lang: Lang) {
  return CLOCK[lang];
}

export function htmlLang(lang: Lang) {
  return lang === "tl" ? "fil" : lang;
}

